# Extra keys that are concatenated at runtime and were missing from the catalog.
EXTRA = [
    'Instala StadiaLink para activar el inicio con Windows.|Install StadiaLink to enable Windows startup.|Installez StadiaLink pour activer le démarrage avec Windows.|Installieren Sie StadiaLink, um den Windows-Autostart zu aktivieren.|安装 StadiaLink 后才能启用随 Windows 启动。',
    '»?|»?| » ?| » ?|」吗？',
]


def main():
    text = CATALOG.read_text(encoding='utf-8-sig')
    lines = [line for line in text.splitlines() if line.strip()]
    extra_keys = {row.split('|')[0] for row in EXTRA}
    # Drop a previously generated Chinese column and the extra rows, so that
    # rerunning the script always produces the same file.
    base = []
    for line in lines:
        fields = line.split('|')
        if fields[0] in extra_keys:
            continue
        if len(fields) == 5:
            fields = fields[:4]
        if len(fields) != 4:
            raise SystemExit('unexpected catalog row: %r' % line)
        base.append(fields)
    if len(base) != len(ZH):
        raise SystemExit('catalog has %d rows but %d translations' % (len(base), len(ZH)))
    for i, zh in enumerate(ZH, 1):
        if not zh.strip() or '|' in zh:
            raise SystemExit('bad Chinese translation at row %d' % i)
    rows = ['|'.join(fields + [zh]) for fields, zh in zip(base, ZH)]
    rows.extend(EXTRA)
    CATALOG.write_text('\ufeff' + '\n'.join(rows) + '\n', encoding='utf-8')
    print('wrote %d rows (%d original + %d extra) with 5 columns' %
          (len(rows), len(base), len(EXTRA)))


if __name__ == '__main__':
    main()
